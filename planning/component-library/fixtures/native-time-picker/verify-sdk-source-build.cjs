const assert = require("node:assert/strict")
const { readFileSync, existsSync } = require("node:fs")
const path = require("node:path")

const repo = path.resolve(__dirname, "../../../..")
const showcase = path.join(repo, "apps/native-showcase")
const { getConfig } = require(require.resolve("expo/config", { paths: [showcase] }))
const { exp } = getConfig(showcase, { skipSDKVersionRequirement: true })

assert.deepEqual(exp.plugins, ["expo-dev-client"])
assert.equal(existsSync(path.join(showcase, "plugins/withNativeSDKSourceBuild.mjs")), false)
assert.doesNotMatch(readFileSync(path.join(repo, "pnpm-workspace.yaml"), "utf8"), /patchedDependencies/)
assert.doesNotMatch(readFileSync(path.join(repo, "pnpm-lock.yaml"), "utf8"), /patch_hash|patchedDependencies/)
assert.equal(require(require.resolve("react-native/package.json", { paths: [showcase] })).version, "0.86.3")
console.log("5 current stock-SDK configuration assertions passed; regenerated projects/linkage remain separate gates")
