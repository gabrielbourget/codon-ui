export const nativeTableResizeMessages = (locale: string) => {
  locale = typeof Intl.Locale === "function" ? new Intl.Locale(locale).toString() : locale
  const key =
    Object.keys(messages).find((key) => key.toLowerCase() === locale.toLowerCase()) ??
    Object.keys(messages).find((key) => key.split("-")[0].toLowerCase() === locale.split("-")[0].toLowerCase()) ??
    "en-US"
  return messages[key]
}
